#!/usr/bin/env python3
"""Generate remote rule sets for the manually supplied rules."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


HOST_RE = re.compile(
    r"^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+"
    r"[a-z]{2,63}$",
    re.IGNORECASE,
)
ROUTES = ("direct", "proxy")
RULE_TYPES = ("DOMAIN", "DOMAIN-SUFFIX")


def load_rules(source: Path) -> dict[str, list[dict[str, str]]]:
    data = json.loads(source.read_text(encoding="utf-8"))
    entries = data.get("entries")
    if not isinstance(entries, list):
        raise ValueError("data/manual-rules.json must contain an entries array")

    grouped: dict[str, list[dict[str, str]]] = {route: [] for route in ROUTES}
    seen: set[tuple[str, str]] = set()
    for index, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            raise ValueError(f"entry {index} is not an object")
        route = entry.get("route")
        rule_type = entry.get("type")
        host = entry.get("host")
        if route not in ROUTES:
            raise ValueError(f"entry {index} has unsupported route: {route!r}")
        if rule_type not in RULE_TYPES:
            raise ValueError(f"entry {index} has unsupported type: {rule_type!r}")
        if not isinstance(host, str) or not HOST_RE.fullmatch(host):
            raise ValueError(f"entry {index} has invalid host: {host!r}")
        normalized_host = host.lower()
        key = (rule_type, normalized_host)
        if key in seen:
            raise ValueError(f"duplicate rule: {rule_type},{normalized_host}")
        seen.add(key)
        grouped[route].append(
            {"type": rule_type, "host": normalized_host}
        )
    return grouped


def render_clash(entries: list[dict[str, str]]) -> str:
    lines = [
        "# Generated by scripts/build_manual_rules.py. Do not edit by hand.",
        "payload:",
    ]
    lines.extend(f'  - "{item["type"]},{item["host"]}"' for item in entries)
    return "\n".join(lines) + "\n"


def render_surge(entries: list[dict[str, str]]) -> str:
    lines = [
        "# Generated by scripts/build_manual_rules.py. Do not edit by hand.",
    ]
    lines.extend(f'{item["type"]},{item["host"]}' for item in entries)
    return "\n".join(lines) + "\n"


def write_or_check(path: Path, content: str, check: bool) -> bool:
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            print(f"out of date: {path.as_posix()}")
            return False
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.as_posix()}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    grouped = load_rules(root / "data" / "manual-rules.json")
    outputs = {
        root / "rules" / "clash" / "manual-direct.yaml": render_clash(grouped["direct"]),
        root / "rules" / "clash" / "manual-proxy.yaml": render_clash(grouped["proxy"]),
        root / "rules" / "surge" / "manual-direct.list": render_surge(grouped["direct"]),
        root / "rules" / "surge" / "manual-proxy.list": render_surge(grouped["proxy"]),
    }
    ok = all(write_or_check(path, content, args.check) for path, content in outputs.items())
    if args.check:
        print("manual rule files are up to date" if ok else "manual rule files need regeneration")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
